package com.umdc.backoffice.config;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.web.servlet.config.annotation.ViewControllerRegistry;
import org.springframework.web.servlet.config.annotation.WebMvcConfigurer;

/**
 * OpenAPI document metadata.
 * <p>
 * The specification is generated by springdoc at runtime from the {@code *Api.java} interfaces
 * ({@code /v3/api-docs} as JSON, {@code /v3/api-docs.yaml} as YAML); nothing about the paths or
 * schemas is declared here. This class only contributes what no single operation owns: the
 * document info, the security schemes and the default security requirement. Public operations
 * opt out with {@code @SecurityRequirements} on the API method.
 * </p>
 */
@Configuration
public class OpenApiConfig implements WebMvcConfigurer {

    /** Name of the scheme for the JWT sent in the {@code Authorization} header. */
    public static final String BEARER_AUTH = "bearerAuth";
    /** Name of the scheme for the session JWT sent in the {@code session-token} header. */
    public static final String SESSION_TOKEN = "sessionToken";

    static final String GENERATED_YAML_PATH = "/v3/api-docs.yaml";
    static final String LEGACY_YAML_PATH = "/api.yaml";
    private static final String SESSION_TOKEN_HEADER = "session-token";

    /**
     * Base OpenAPI definition that springdoc completes with the scanned operations.
     *
     * @param title   the API title
     * @param version the API version
     * @return the base OpenAPI definition
     */
    @Bean
    public OpenAPI backboneOpenApi(@Value("${umdc.app.title:Backbone REST API}") String title,
                                   @Value("${umdc.app.version:}") String version) {
        return new OpenAPI()
                .info(new Info()
                        .title(title)
                        .version(version)
                        .description("backbone-rest Backoffice REST Service. All endpoints under /api/v1/* require "
                                + "a valid JWT unless the operation declares no security requirement."))
                .components(new Components()
                        .addSecuritySchemes(BEARER_AUTH, new SecurityScheme()
                                .type(SecurityScheme.Type.HTTP)
                                .scheme("bearer")
                                .bearerFormat("JWT")
                                .description("Standard Bearer JWT token in the Authorization header"))
                        .addSecuritySchemes(SESSION_TOKEN, new SecurityScheme()
                                .type(SecurityScheme.Type.APIKEY)
                                .in(SecurityScheme.In.HEADER)
                                .name(SESSION_TOKEN_HEADER)
                                .description("Session JWT issued by the backbone-rest session service")))
                .addSecurityItem(new SecurityRequirement().addList(BEARER_AUTH));
    }

    /**
     * Keeps the former static spec URL working: {@code /api.yaml} now redirects to the generated document.
     *
     * @param registry the view controller registry
     */
    @Override
    public void addViewControllers(ViewControllerRegistry registry) {
        registry.addRedirectViewController(LEGACY_YAML_PATH, GENERATED_YAML_PATH);
    }
}
